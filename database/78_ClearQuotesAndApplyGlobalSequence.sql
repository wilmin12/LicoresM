-- Port Additional Charges
DELETE FROM FF_QUOTE_INL_PORT_ADD;

-- Ocean Charges
DELETE FROM FF_QUOTE_OCEAN_CHARGE;
DELETE FROM FF_QUOTE_INL_REGION_TYPE;
DELETE FROM FF_QUOTE_OCEAN_PORT;

-- Header (La tabla principal)
DELETE FROM FF_QUOTE_HEADER;
GO

-- Eliminar la restricción antigua (si aún existe)
IF EXISTS (SELECT * FROM sys.objects WHERE name = 'UQ_FF_QUOTE_HEADER_Num_Type' AND type = 'UQ')
BEGIN
    ALTER TABLE FF_QUOTE_HEADER DROP CONSTRAINT UQ_FF_QUOTE_HEADER_Num_Type;
END
GO

-- Crear la nueva restricción única global
ALTER TABLE FF_QUOTE_HEADER ADD CONSTRAINT UQ_FF_QUOTE_HEADER_Num_Global UNIQUE (FQH_QUOTE_NUMBER);
GO
