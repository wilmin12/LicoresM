DELETE FROM FF_QUOTE_LCL_PORT_TYPE;
DELETE FROM FF_QUOTE_LCL_PORT;

-- Inland Charges
DELETE FROM FF_QUOTE_INLAND_REGION_TYPE_DETAIL;
